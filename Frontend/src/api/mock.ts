// Mirrors the backend Pydantic ISATVON contract, field by field.
export function validateField(field: IsatvonField, value: string): string | undefined {
  const v = value.trim()
  switch (field) {
    case 'instructions':
      return v.length < 15 ? 'value_error: at least 15 characters of business logic required' : undefined
    case 'sourceData':
      return /^(s3|db|https?|file|sheet):\/\/\S+/.test(v) ? undefined : 'value_error: must be a URI (s3://, db://, https://, file://, sheet://)'
    case 'automation':
      return (AUTOMATIONS as readonly string[]).includes(v) ? undefined : `enum_error: expected one of ${AUTOMATIONS.join(', ')}`
    case 'techStack':
      return v ? undefined : 'missing: at least one library or runtime is required'
    case 'variables': {
      const bad = v.split(';').map(p => p.trim()).filter(Boolean).find(p => !/^[A-Za-z_]\w*\s*:\s*\S/.test(p))
      return bad ? `value_error: "${bad}" is not "key: value"` : undefined
    }
    case 'outcome':
      return v ? undefined : 'missing: outcome schema is required'
    case 'notifications':
      return undefined
  }
}

const validateRow = (fields: SkillRow['fields']) =>
  Object.fromEntries(ISATVON.map(c => [c.key, validateField(c.key, fields[c.key])]).filter(([, e]) => e)) as SkillRow['errors']

function parseVars(v: string) {
  return v.split(';').map(p => p.trim()).filter(Boolean).map(p => {
    const i = p.indexOf(':')
    return [p.slice(0, i).trim(), p.slice(i + 1).trim()] as const
  })
}

// Stand-in for the .py.j2 template. `quoteFormulas` is what activity D's
// LLM self-correction fixes: the template emits spreadsheet formulas raw.
function renderSkill(s: SkillRow, version: string, sowVersion: number, quoteFormulas: boolean) {
  const value = (v: string) => /^-?\d+(\.\d+)?$/.test(v) ? v : v.startsWith('=') && !quoteFormulas ? v : `"${pyStr(v)}"`
  const f = s.fields
  return [
    `# Generated by BAM from the ISATVON contract ${version}`,
    `# Agent > Skill: ${s.agent} > ${s.name} (${s.id})`,
    `# Source: SOW v${sowVersion}, passage ${s.passageId}`,
    'from pydantic import BaseModel',
    '',
    `SKILL_ID = "${s.id}"`,
    `AUTOMATION = "${f.automation}"`,
    `TECH_STACK = [${f.techStack.split(',').map(t => `"${pyStr(t.trim())}"`).join(', ')}]`,
    `SOURCE_DATA = "${pyStr(f.sourceData)}"`,
    'VARIABLES = {',
    ...parseVars(f.variables).map(([k, v]) => `    "${pyStr(k)}": ${value(v)},`),
    '}',
    '',
    '',
    'class Outcome(BaseModel):',
    `    """${f.outcome.replace(/"""/g, "'''")}"""`,
    '    status: str',
    '    payload: dict',
    '',
    '',
    'def run(payload: dict) -> Outcome:',
    `    """${f.instructions.replace(/"""/g, "'''")}"""`,
    '    return Outcome(status="ok", payload={"variables": VARIABLES, **payload})',
    '',
  ].join('\n')
}

// ponytail: stand-in for ast.parse(); only catches the unquoted-formula case the template can produce.
const astErrors = (code: string) =>
  code.split('\n').flatMap((l, i) => /^\s+"[^"]+": =/.test(l) ? [{ line: i + 1, msg: 'SyntaxError: invalid syntax (unquoted spreadsheet formula in VARIABLES)' }] : [])

async function sha256(text: string) {
  const buf = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text))
  return [...new Uint8Array(buf)].map(b => b.toString(16).padStart(2, '0')).join('')
}

